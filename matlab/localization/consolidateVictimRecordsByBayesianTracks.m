function [mergedTracks, clusterIndex, clusterDiameters, ...
        compactClusterIndex, compactClusterDiameters, ...
        absorbedFragmentTrackMask, ...
        fragmentTargetCompactClusterIndex, ...
        fragmentRejectedByDiameterTrackMask, ...
        fragmentRejectedByMeasurementResolutionTrackMask] = ...
    clusterConfirmedTracks( ...
        tracks, ...
        mergeDistance, ...
        maximumEdgeDistance, ...
        maximumMahalanobisDistance, ...
        maximumClusterDiameter, ...
        fragmentAssociationDistance, ...
        fragmentAssociationAmbiguityMargin, ...
        fragmentMinimumCoreMembers, ...
        minimumIndependentViewDistance, ...
        minimumResolvedRangedViews, ...
        resolvedSourceMinimumSeparation)

numberOfTracks = numel(tracks);
clusterIndex = zeros(numberOfTracks,1);
clusterDiameters = zeros(0,1);
compactClusterIndex = zeros(numberOfTracks,1);
compactClusterDiameters = zeros(0,1);
absorbedFragmentTrackMask = false(numberOfTracks,1);
fragmentTargetCompactClusterIndex = zeros(numberOfTracks,1);
fragmentRejectedByDiameterTrackMask = false(numberOfTracks,1);
fragmentRejectedByMeasurementResolutionTrackMask = ...
    false(numberOfTracks,1);
mergedTracks = tracks([]);

if numberOfTracks == 0
    return;
end

positions = reshape([tracks.position], 2, [])';
clusterCount = 0;

for seedIndex = 1:numberOfTracks

    if clusterIndex(seedIndex) > 0
        continue;
    end

    clusterCount = clusterCount + 1;
    clusterIndex(seedIndex) = clusterCount;
    clusterMembers = seedIndex;

    while true

        candidateIndices = find(clusterIndex == 0);
        bestCandidateIndex = 0;
        bestLinkDistance = inf;

        for candidateIndex = candidateIndices(:)'
            memberOffsets = ...
                positions(clusterMembers,:) - ...
                positions(candidateIndex,:);
            memberDistances = hypot( ...
                memberOffsets(:,1), ...
                memberOffsets(:,2));
            [euclideanDistance, nearestMemberOffset] = ...
                min(memberDistances);
            currentIndex = ...
                clusterMembers(nearestMemberOffset);

            isInsideFixedGate = ...
                euclideanDistance <= mergeDistance;
            isInsideUncertaintyGate = false;

            if ~isInsideFixedGate && ...
                    euclideanDistance <= maximumEdgeDistance
                mahalanobisDistance = ...
                    calculateTrackMahalanobisDistance( ...
                        tracks(currentIndex), ...
                        tracks(candidateIndex));
                isInsideUncertaintyGate = ...
                    mahalanobisDistance <= ...
                    maximumMahalanobisDistance;
            end

            proposedDiameter = max(memberDistances);
            preservesClusterDiameter = ...
                proposedDiameter <= maximumClusterDiameter;

            if (isInsideFixedGate || ...
                    isInsideUncertaintyGate) && ...
                    preservesClusterDiameter && ...
                    euclideanDistance < bestLinkDistance
                bestCandidateIndex = candidateIndex;
                bestLinkDistance = euclideanDistance;
            end
        end

        if bestCandidateIndex == 0
            break;
        end

        clusterIndex(bestCandidateIndex) = clusterCount;
        clusterMembers(end+1,1) = ... %#ok<AGROW>
            bestCandidateIndex;

    end

end


compactClusterIndex = clusterIndex;

for currentCluster = 1:clusterCount
    groupPositions = positions( ...
        compactClusterIndex == currentCluster,:);
    compactClusterDiameters(currentCluster,1) = ... %#ok<AGROW>
        calculatePositionDiameter(groupPositions);
end

[clusterIndex, absorbedFragmentTrackMask, ...
        fragmentTargetCompactClusterIndex, ...
        fragmentRejectedByDiameterTrackMask, ...
        fragmentRejectedByMeasurementResolutionTrackMask] = ...
    reconcileSingletonTrackFragments( ...
        tracks, ...
        compactClusterIndex, ...
        fragmentAssociationDistance, ...
        fragmentAssociationAmbiguityMargin, ...
        fragmentMinimumCoreMembers, ...
        maximumClusterDiameter, ...
        minimumIndependentViewDistance, ...
        minimumResolvedRangedViews, ...
        resolvedSourceMinimumSeparation);

finalClusterIDs = unique(clusterIndex, 'stable');
renumberedClusterIndex = zeros(size(clusterIndex));

for finalCluster = 1:numel(finalClusterIDs)
    renumberedClusterIndex( ...
        clusterIndex == finalClusterIDs(finalCluster)) = ...
        finalCluster;
end

clusterIndex = renumberedClusterIndex;
clusterCount = numel(finalClusterIDs);


for currentCluster = 1:clusterCount
    group = tracks(clusterIndex == currentCluster);
    groupPositions = reshape([group.position], 2, [])';
    clusterDiameters(currentCluster,1) = ... %#ok<AGROW>
        calculatePositionDiameter(groupPositions);
    mergedTracks(end+1,1) = mergeTrackGroup( ... %#ok<AGROW>
        group, minimumIndependentViewDistance);
end

end


function [reconciledClusterIndex, absorbedTrackMask, ...
        fragmentTargetCompactClusterIndex, ...
        rejectedByDiameterTrackMask, ...
        rejectedByMeasurementResolutionTrackMask] = ...
    reconcileSingletonTrackFragments( ...
        tracks, ...
        compactClusterIndex, ...
        maximumFragmentDistance, ...
        ambiguityMargin, ...
        minimumCoreMembers, ...
        maximumClusterDiameter, ...
        minimumIndependentViewDistance, ...
        minimumResolvedRangedViews, ...
        resolvedSourceMinimumSeparation)
% تعيد عنقودًا منفردًا إلى أقرب عنقود مدمج ومدعوم فقط. تستخدم
% مراكز العناقيد المدمجة الأصلية مرة واحدة، ولذلك لا تستطيع الشظية
% الممتصة أن تعمل كحلقة جديدة في سلسلة اتصال بين ضحيتين. كما أن
% كل امتصاص يجب أن يحافظ على حد القطر التراكمي للعنقود؛ فلا يجوز
% لشظيتين مقبولتين منفردتين أن تمددا النواة من طرفين مختلفين.

reconciledClusterIndex = compactClusterIndex;
absorbedTrackMask = false(numel(tracks),1);
fragmentTargetCompactClusterIndex = ...
    zeros(numel(tracks),1);
rejectedByDiameterTrackMask = false(numel(tracks),1);
rejectedByMeasurementResolutionTrackMask = ...
    false(numel(tracks),1);

if maximumFragmentDistance <= 0 || isempty(tracks)
    return;
end

compactClusterIDs = unique(compactClusterIndex, 'stable');
numberOfCompactClusters = numel(compactClusterIDs);
compactClusterCounts = zeros(numberOfCompactClusters,1);
compactRepresentatives = zeros(numberOfCompactClusters,2);

for compactOffset = 1:numberOfCompactClusters
    compactClusterID = compactClusterIDs(compactOffset);
    memberMask = compactClusterIndex == compactClusterID;
    compactClusterCounts(compactOffset) = nnz(memberMask);
    compactTrack = mergeTrackGroup( ...
        tracks(memberMask), ...
        minimumIndependentViewDistance);
    compactRepresentatives(compactOffset,:) = ...
        compactTrack.position(1:2);
end

coreOffsets = find( ...
    compactClusterCounts >= minimumCoreMembers);

if isempty(coreOffsets)
    return;
end

fragmentOffsets = find(compactClusterCounts == 1);

for fragmentOffset = fragmentOffsets(:)'
    fragmentClusterID = ...
        compactClusterIDs(fragmentOffset);
    fragmentPosition = ...
        compactRepresentatives(fragmentOffset,:);
    coreOffsetsFromFragment = ...
        compactRepresentatives(coreOffsets,:) - ...
        fragmentPosition;
    coreDistances = hypot( ...
        coreOffsetsFromFragment(:,1), ...
        coreOffsetsFromFragment(:,2));
    [sortedDistances, sortedOffsets] = ...
        sort(coreDistances, 'ascend');

    nearestDistance = sortedDistances(1);
    hasUniqueTarget = numel(sortedDistances) == 1 || ...
        sortedDistances(2) - nearestDistance >= ...
        ambiguityMargin;

    if nearestDistance > maximumFragmentDistance || ...
            ~hasUniqueTarget
        continue;
    end

    targetCoreOffset = ...
        coreOffsets(sortedOffsets(1));
    targetCompactClusterID = ...
        compactClusterIDs(targetCoreOffset);
    fragmentTrackMask = ...
        compactClusterIndex == fragmentClusterID;
    targetTrackMask = ...
        reconciledClusterIndex == targetCompactClusterID;
    proposedTrackMask = ...
        targetTrackMask | fragmentTrackMask;
    proposedPositions = reshape( ...
        [tracks(proposedTrackMask).position],2,[])';
    proposedDiameter = ...
        calculatePositionDiameter(proposedPositions);

    fragmentTrack = tracks(fragmentTrackMask);
    targetTracks = tracks(targetTrackMask);
    fragmentIsResolved = ...
        fragmentTrack.independentRangedViewCount >= ...
        minimumResolvedRangedViews;
    targetIsResolved = any( ...
        [targetTracks.independentRangedViewCount] >= ...
        minimumResolvedRangedViews);
    preservesResolvedSources = ~( ...
        fragmentIsResolved && targetIsResolved && ...
        nearestDistance >= ...
            resolvedSourceMinimumSeparation);

    if ~preservesResolvedSources
        rejectedByMeasurementResolutionTrackMask( ...
            fragmentTrackMask) = true;
        continue;
    end

    if proposedDiameter > maximumClusterDiameter
        rejectedByDiameterTrackMask(fragmentTrackMask) = true;
        continue;
    end

    reconciledClusterIndex(fragmentTrackMask) = ...
        targetCompactClusterID;
    absorbedTrackMask(fragmentTrackMask) = true;
    fragmentTargetCompactClusterIndex(fragmentTrackMask) = ...
        targetCompactClusterID;
end

end


