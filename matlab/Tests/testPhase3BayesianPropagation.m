%% ============================================================
% Test Geometric Distance
%% ============================================================

function testGeometricDistanceIsCorrect(testCase)

scenario = buildSyntheticScenario();

probePosition = [2 3];
candidatePosition = [5 7];

context = bayesianPropagationContext( ...
    scenario, ...
    probePosition, ...
    candidatePosition);

verifyEqual( ...
    testCase, ...
    context.distance, ...
    5, ...
    'AbsTol', ...
    1e-12);
% المسافة بين النقطتين تمثل مثلث 3-4-5

verifyEqual( ...
    testCase, ...
    context.probePosition, ...
    probePosition);

verifyEqual( ...
    testCase, ...
    context.candidatePosition, ...
    candidatePosition);

verifyGreaterThanOrEqual( ...
    testCase, ...
    context.pathCellCount, ...
    2);

end

%% ============================================================
% Test Environmental Values Are Bounded
%% ============================================================

function testEnvironmentalValuesRemainBounded(testCase)

scenario = buildSyntheticScenario();

context = bayesianPropagationContext( ...
    scenario, ...
    [1 1], ...
    [10 12]);

environmentValues = [ ...
    context.meanDebris, ...
    context.meanAttenuation, ...
    context.meanNoise, ...
    context.obstacleFraction];

verifyGreaterThanOrEqual( ...
    testCase, ...
    environmentValues, ...
    zeros(size(environmentValues)));

verifyLessThanOrEqual( ...
    testCase, ...
    environmentValues, ...
    ones(size(environmentValues)));

end

%% ============================================================
% Test Ground Truth Independence
%% ============================================================

function testGroundTruthDoesNotAffectPropagation(testCase)

scenarioA = buildSyntheticScenario();

scenarioB = scenarioA;

scenarioB.victims = [ ...
    1 1;
    10 12;
    5 6];
% تغيير مواقع الضحايا الحقيقية بالكامل

scenarioB.groundTruth.locations = [ ...
    2 11;
    9 2;
    7 7];
% تغيير Ground Truth

scenarioB.environment.vitalSigns = ...
    rand(scenarioB.gridSize);
% تغيير خريطة الإشارات الحيوية المخفية

contextA = bayesianPropagationContext( ...
    scenarioA, ...
    [3 4], ...
    [8 10]);

contextB = bayesianPropagationContext( ...
    scenarioB, ...
    [3 4], ...
    [8 10]);

verifyEqual( ...
    testCase, ...
    contextA, ...
    contextB);
% يجب أن يبقى السياق مطابقًا لأن الدالة لا تستخدم الحقيقة المخفية

end

%% ============================================================
