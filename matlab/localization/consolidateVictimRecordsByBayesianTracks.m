function [victims, finalPeaks, report] = ...
    consolidateVictimRecordsByBayesianTracks( ...
        victims, ...
        bayesianState)
%% ============================================================
% تثبيت قاعدة الضحايا باستخدام المسارات البايزية المؤكدة فقط.
% لا تستخدم الدالة Ground Truth أو عدد الضحايا الحقيقي.
%% ============================================================

inputRecordCount = numel(victims);
finalPeaks = emptyFinalPeakArray();
report = createReport(inputRecordCount);

if ~isempty(victims)
    report.inputRecordPositions = reshape( ...
        [victims.position], 2, [])';
end

if ~isstruct(bayesianState) || ...
        ~isfield(bayesianState, 'tracks') || ...
        isempty(bayesianState.tracks)
    victims = victims([]);
    return;
end

tracks = normalizeMeasurementResolvedTrackSchema( ...
    bayesianState.tracks);
confirmedMask = false(numel(tracks),1);

for index = 1:numel(tracks)
    confirmedMask(index) = ...
        string(tracks(index).status) == "CONFIRMED";
end

confirmedTracks = tracks(confirmedMask);
rawConfirmedTracks = confirmedTracks;
% الاحتفاظ بأعضاء المسارات الخام لاستخدامها كمراسي مكانية بعد الدمج.
report.rawConfirmedTrackCount = numel(confirmedTracks);

if ~isempty(confirmedTracks)
    report.rawConfirmedTrackPositions = reshape( ...
        [confirmedTracks.position], 2, [])';
end

if isempty(confirmedTracks)
    victims = victims([]);
    return;
end

config = constants();
if isfield(bayesianState, 'localizationMethod') && ...
        lower(string(bayesianState.localizationMethod)) == ...
        "spatialbayesianfusion"
    bayesianConfig = config.spatialBayesian;
else
    bayesianConfig = config.bayesian;
end

trackAssociationDistance = ...
    bayesianConfig.trackAssociationDistance;
if isfield(bayesianConfig, 'trackConsolidationDistance')
    trackConsolidationDistance = ...
        bayesianConfig.trackConsolidationDistance;
else
    trackConsolidationDistance = ...
        trackAssociationDistance;
end

if isfield(bayesianConfig, ...
        'trackConsolidationMaximumEdgeDistance')
    trackConsolidationMaximumEdgeDistance = ...
        bayesianConfig.trackConsolidationMaximumEdgeDistance;
else
    trackConsolidationMaximumEdgeDistance = ...
        trackConsolidationDistance;
end

if isfield(bayesianConfig, ...
        'trackConsolidationMaximumMahalanobisDistance')
    trackConsolidationMaximumMahalanobisDistance = ...
        bayesianConfig.trackConsolidationMaximumMahalanobisDistance;
else
    trackConsolidationMaximumMahalanobisDistance = 0;
end

if isfield(bayesianConfig, ...
        'trackConsolidationMaximumClusterDiameter')
    trackConsolidationMaximumClusterDiameter = ...
        bayesianConfig.trackConsolidationMaximumClusterDiameter;
else
    trackConsolidationMaximumClusterDiameter = inf;
end

if isfield(bayesianConfig, ...
        'trackFragmentAssociationDistance')
    trackFragmentAssociationDistance = ...
        bayesianConfig.trackFragmentAssociationDistance;
else
    trackFragmentAssociationDistance = 0;
end

if isfield(bayesianConfig, ...
        'trackFragmentAssociationAmbiguityMargin')
    trackFragmentAssociationAmbiguityMargin = ...
        bayesianConfig.trackFragmentAssociationAmbiguityMargin;
else
    trackFragmentAssociationAmbiguityMargin = inf;
end

if isfield(bayesianConfig, ...
        'trackFragmentMinimumCoreMembers')
    trackFragmentMinimumCoreMembers = ...
        bayesianConfig.trackFragmentMinimumCoreMembers;
else
    trackFragmentMinimumCoreMembers = 2;
end

if isfield(bayesianConfig, ...
        'trackBasinMaximumValleyDrop')
    trackBasinMaximumValleyDrop = ...
        bayesianConfig.trackBasinMaximumValleyDrop;
else
    trackBasinMaximumValleyDrop = -inf;
end

if isfield(bayesianConfig, ...
        'trackBasinMaximumPeakDistance')
    trackBasinMaximumPeakDistance = ...
        bayesianConfig.trackBasinMaximumPeakDistance;
else
    trackBasinMaximumPeakDistance = inf;
end

if isfield(bayesianConfig, ...
        'trackBasinPeakSearchRadius')
    trackBasinPeakSearchRadius = ...
        bayesianConfig.trackBasinPeakSearchRadius;
else
    trackBasinPeakSearchRadius = 0;
end

if isfield(bayesianConfig, ...
        'trackBasinMinimumPeakLogOdds')
    trackBasinMinimumPeakLogOdds = ...
        bayesianConfig.trackBasinMinimumPeakLogOdds;
else
    trackBasinMinimumPeakLogOdds = inf;
end

if isfield(bayesianConfig, ...
        'trackBasinLineSamplesPerCell')
    trackBasinLineSamplesPerCell = ...
        bayesianConfig.trackBasinLineSamplesPerCell;
else
    trackBasinLineSamplesPerCell = 5;
end

if isfield(bayesianConfig, ...
        'trackBasinMinimumSupportRetention')
    trackBasinMinimumSupportRetention = ...
        bayesianConfig.trackBasinMinimumSupportRetention;
else
    trackBasinMinimumSupportRetention = 0;
end

if isfield(bayesianConfig, ...
        'weakIsolatedBasinMinimumLogOddsGap')
    weakIsolatedBasinMinimumLogOddsGap = ...
        bayesianConfig.weakIsolatedBasinMinimumLogOddsGap;
else
    weakIsolatedBasinMinimumLogOddsGap = inf;
end

if isfield(bayesianConfig, ...
        'weakIsolatedBasinMaximumRelativeSupport')
    weakIsolatedBasinMaximumRelativeSupport = ...
        bayesianConfig.weakIsolatedBasinMaximumRelativeSupport;
else
    weakIsolatedBasinMaximumRelativeSupport = 0;
end

if isfield(bayesianConfig, ...
        'weakIsolatedBasinMaximumRawTracks')
    weakIsolatedBasinMaximumRawTracks = ...
        bayesianConfig.weakIsolatedBasinMaximumRawTracks;
else
    weakIsolatedBasinMaximumRawTracks = 0;
end

if isfield(bayesianConfig,'weakMapBasinMaximumRawTracks')
    weakMapBasinMaximumRawTracks = ...
        bayesianConfig.weakMapBasinMaximumRawTracks;
else
    weakMapBasinMaximumRawTracks = 0;
end
if isfield(bayesianConfig,'weakMapBasinMinimumLogOddsGap')
    weakMapBasinMinimumLogOddsGap = ...
        bayesianConfig.weakMapBasinMinimumLogOddsGap;
else
    weakMapBasinMinimumLogOddsGap = inf;
end
if isfield(bayesianConfig, ...
        'weakMapBasinMaximumRelativeSupport')
    weakMapBasinMaximumRelativeSupport = ...
        bayesianConfig.weakMapBasinMaximumRelativeSupport;
else
    weakMapBasinMaximumRelativeSupport = 0;
end

if isfield(bayesianConfig, ...
        'minimumResolvedRangedViews')
    minimumResolvedRangedViews = ...
        bayesianConfig.minimumResolvedRangedViews;
else
    minimumResolvedRangedViews = inf;
end

if isfield(bayesianConfig, ...
        'resolvedSourceMinimumSeparation')
    resolvedSourceMinimumSeparation = ...
        bayesianConfig.resolvedSourceMinimumSeparation;
else
    resolvedSourceMinimumSeparation = inf;
end

if isfield(bayesianConfig,'resolvedSourceSoftPeakSeparation')
    resolvedSourceSoftPeakSeparation = ...
        bayesianConfig.resolvedSourceSoftPeakSeparation;
else
    resolvedSourceSoftPeakSeparation = ...
        resolvedSourceMinimumSeparation;
end
if isfield(bayesianConfig, ...
        'resolvedSourceMaximumBridgeRetention')
    resolvedSourceMaximumBridgeRetention = ...
        bayesianConfig.resolvedSourceMaximumBridgeRetention;
else
    resolvedSourceMaximumBridgeRetention = 0;
end

[confirmedTracks, trackClusterIndex, ...
        trackClusterDiameters, ...
        compactTrackClusterIndex, ...
        compactTrackClusterDiameters, ...
        absorbedFragmentTrackMask, ...
        fragmentTargetCompactClusterIndex, ...
        fragmentRejectedByDiameterTrackMask, ...
        fragmentRejectedByMeasurementResolutionTrackMask] = ...
    clusterConfirmedTracks( ...
        confirmedTracks, ...
        trackConsolidationDistance, ...
        trackConsolidationMaximumEdgeDistance, ...
        trackConsolidationMaximumMahalanobisDistance, ...
        trackConsolidationMaximumClusterDiameter, ...
        trackFragmentAssociationDistance, ...
        trackFragmentAssociationAmbiguityMargin, ...
        trackFragmentMinimumCoreMembers, ...
        bayesianConfig.minimumIndependentViewDistance, ...
        minimumResolvedRangedViews, ...
        resolvedSourceMinimumSeparation);
% الدمج هنا يعمل على المسارات المؤكدة نفسها قبل مطابقة سجلات الضحايا.
% المرحلة الأولى تكوّن عناقيد مدمجة محدودة القطر. المرحلة الثانية
% تعيد الشظية المنفردة فقط إلى عنقود مدعوم، دون السماح لها بنقل
% الاتصال إلى عنقود آخر أو دمج عنقودين مدعومين مستقلين.

preBasinTrackClusterIndex = trackClusterIndex;
preBasinTrackClusterDiameters = trackClusterDiameters;
basinDiagnostics = createEmptyBasinDiagnostics( ...
    numel(confirmedTracks));

if isfield(bayesianState, 'logOddsMap') && ...
        ~isempty(bayesianState.logOddsMap)
    [confirmedTracks, trackClusterIndex, ...
            trackClusterDiameters, basinDiagnostics] = ...
        consolidateTrackClustersByLogOddsBasins( ...
            rawConfirmedTracks, ...
            confirmedTracks, ...
            trackClusterIndex, ...
            bayesianState.logOddsMap, ...
            bayesianState.weightedObservationSupport, ...
            trackBasinMaximumValleyDrop, ...
            trackBasinMaximumPeakDistance, ...
            trackBasinPeakSearchRadius, ...
            trackBasinMinimumPeakLogOdds, ...
            trackBasinLineSamplesPerCell, ...
            trackBasinMinimumSupportRetention, ...
            weakIsolatedBasinMinimumLogOddsGap, ...
            weakIsolatedBasinMaximumRelativeSupport, ...
            weakIsolatedBasinMaximumRawTracks, ...
            weakMapBasinMinimumLogOddsGap, ...
            weakMapBasinMaximumRelativeSupport, ...
            weakMapBasinMaximumRawTracks, ...
            bayesianConfig.minimumIndependentViewDistance, ...
            minimumResolvedRangedViews, ...
            resolvedSourceMinimumSeparation, ...
            resolvedSourceSoftPeakSeparation, ...
            resolvedSourceMaximumBridgeRetention);
end

report.confirmedTrackCount = numel(confirmedTracks);
report.trackClusterIndex = trackClusterIndex;
report.trackClusterDiameters = trackClusterDiameters;
report.compactTrackClusterIndex = compactTrackClusterIndex;
report.compactTrackClusterDiameters = ...
    compactTrackClusterDiameters;
report.absorbedFragmentTrackMask = ...
    absorbedFragmentTrackMask;
report.fragmentTargetCompactClusterIndex = ...
    fragmentTargetCompactClusterIndex;
report.fragmentRejectedByDiameterTrackMask = ...
    fragmentRejectedByDiameterTrackMask;
report.fragmentRejectedByMeasurementResolutionTrackMask = ...
    fragmentRejectedByMeasurementResolutionTrackMask;
report.preBasinTrackClusterIndex = ...
    preBasinTrackClusterIndex;
report.preBasinTrackClusterDiameters = ...
    preBasinTrackClusterDiameters;
report.basinPeakPositions = ...
    basinDiagnostics.peakPositions;
report.basinPeakLogOdds = ...
    basinDiagnostics.peakLogOdds;
report.basinPeakSupport = ...
    basinDiagnostics.peakSupport;
report.basinPairwisePeakDistances = ...
    basinDiagnostics.pairwisePeakDistances;
report.basinPairwiseValleyDrops = ...
    basinDiagnostics.pairwiseValleyDrops;
report.basinPairwiseSupportRetention = ...
    basinDiagnostics.pairwiseSupportRetention;
report.basinPairwiseTemporalContainment = ...
    basinDiagnostics.pairwiseTemporalContainment;
report.basinPairwiseTemporalJaccard = ...
    basinDiagnostics.pairwiseTemporalJaccard;
report.basinIndependentRangedViewCounts = ...
    basinDiagnostics.independentRangedViewCounts;
report.basinPairwiseMeasurementResolvedVeto = ...
    basinDiagnostics.pairwiseMeasurementResolvedVeto;
report.basinPreToFinalClusterIndex = ...
    basinDiagnostics.preToFinalClusterIndex;
report.basinMergedClusterCount = ...
    basinDiagnostics.mergedClusterCount;
report.basinRejectedPreClusterMask = ...
    basinDiagnostics.rejectedPreClusterMask;
report.basinRejectedClusterCount = ...
    basinDiagnostics.rejectedClusterCount;
report.consolidatedTrackPositions = reshape( ...
    [confirmedTracks.position], 2, [])';

for index = 1:numel(confirmedTracks)
    track = confirmedTracks(index);
    finalPeaks(end+1,1) = struct( ...
        'row', round(track.position(1)), ...
        'column', round(track.position(2)), ...
        'value', track.existenceProbability, ...
        'prominence', track.maximumProbability, ...
        'selectionScore', track.existenceProbability, ...
        'probability', track.existenceProbability, ...
        'uncertaintyRadius', sqrt(max( ...
            eps, trace(track.covariance)))); %#ok<AGROW>
end

if isempty(victims)
    return;
end

maximumDistance = max( ...
    trackAssociationDistance, ...
    config.victimDatabase.associationDistance);
assignments = zeros(numel(victims),1);
assignmentDistances = inf(numel(victims),1);
assignmentGates = zeros(numel(victims),1);
assignmentAnchorTrackID = zeros(numel(victims),1);
usedUncertaintyRescue = false(numel(victims),1);

if isfield(bayesianConfig, ...
        'recordAssociationUncertaintyScale')
    uncertaintyScale = ...
        bayesianConfig.recordAssociationUncertaintyScale;
else
    uncertaintyScale = 0;
end

if isfield(bayesianConfig, ...
        'maximumRecordAssociationDistance')
    maximumRecordAssociationDistance = ...
        bayesianConfig.maximumRecordAssociationDistance;
else
    maximumRecordAssociationDistance = maximumDistance;
end

%% ============================================================
% Stage 1: Conservative Fixed-Gate Association
%% ============================================================

for victimIndex = 1:numel(victims)
    position = victims(victimIndex).position(1:2);

    for trackIndex = 1:numel(confirmedTracks)
        [distance, anchorTrackID] = ...
            calculateRecordToClusterDistance( ...
                position, ...
                trackIndex, ...
                rawConfirmedTracks, ...
                trackClusterIndex, ...
                confirmedTracks(trackIndex));

        if distance <= maximumDistance && ...
                distance < assignmentDistances(victimIndex)
            assignments(victimIndex) = trackIndex;
            assignmentDistances(victimIndex) = distance;
            assignmentGates(victimIndex) = maximumDistance;
            assignmentAnchorTrackID(victimIndex) = ...
                anchorTrackID;
        end
    end
end

%% ============================================================
% Stage 2: Unambiguous Singleton Uncertainty Rescue
%% ============================================================
% لا تُوسع بوابة المطابقة في المشاهد متعددة السجلات أو المسارات، لأن
% عدم يقين مسار زائف قد يحوله إلى كشف نهائي. يسمح بالإنقاذ فقط عندما
% يوجد سجل واحد ومسار مؤكد واحد وفشلت البوابة الثابتة.

isSingletonAssociation = ...
    numel(victims) == 1 && ...
    numel(confirmedTracks) == 1;

if isSingletonAssociation && assignments(1) == 0
    position = victims(1).position(1:2);
    track = confirmedTracks(1);
    uncertaintyRadius = sqrt(max( ...
        eps, trace(track.covariance)));
    expandedGate = min( ...
        maximumRecordAssociationDistance, ...
        maximumDistance + ...
            uncertaintyScale * uncertaintyRadius);
    [distance, anchorTrackID] = ...
        calculateRecordToClusterDistance( ...
            position, ...
            1, ...
            rawConfirmedTracks, ...
            trackClusterIndex, ...
            track);

    if distance <= expandedGate
        assignments(1) = 1;
        assignmentDistances(1) = distance;
        assignmentGates(1) = expandedGate;
        assignmentAnchorTrackID(1) = anchorTrackID;
        usedUncertaintyRescue(1) = true;
    end
end


consolidatedVictims = victims([]);

for trackIndex = 1:numel(confirmedTracks)
    recordIndices = find(assignments == trackIndex);
    if isempty(recordIndices)
        continue;
    end

    track = confirmedTracks(trackIndex);
    assignedRecords = victims(recordIndices);
    [~, baseIndex] = max([assignedRecords.priorityScore]);
    consolidatedVictim = assignedRecords(baseIndex);
    consolidatedVictim.position = round(track.position(1:2));
    consolidatedVictim.vitalityIndex = median( ...
        [assignedRecords.vitalityIndex]);
    consolidatedVictim.victimCondition = ...
        estimateVictimCondition( ...
            consolidatedVictim.vitalityIndex);
    consolidatedVictim.priorityScore = max( ...
        [assignedRecords.priorityScore]);
    consolidatedVictim.independentViewCount = ...
        track.independentViewCount;
    consolidatedVictim.detectionCount = ...
        track.independentViewCount;
    consolidatedVictim.rawAssociationCount = sum( ...
        [assignedRecords.rawAssociationCount]);
    if isfield(assignedRecords, ...
            'hasRangedMeasurementEvidence')
        consolidatedVictim.hasRangedMeasurementEvidence = ...
            any(logical([ ...
                assignedRecords.hasRangedMeasurementEvidence]));
    end
    if isfield(assignedRecords, ...
            'rangedMeasurementAssociationCount')
        consolidatedVictim.rangedMeasurementAssociationCount = ...
            sum([ ...
                assignedRecords.rangedMeasurementAssociationCount]);
    end

    allObservationPositions = zeros(0,2);
    for recordIndex = 1:numel(assignedRecords)
        allObservationPositions = [ ...
            allObservationPositions; ...
            assignedRecords(recordIndex).observationPositions]; %#ok<AGROW>
    end
    allObservationPositions = unique( ...
        allObservationPositions, ...
        'rows', ...
        'stable');
    consolidatedVictim.observationPositions = ...
        allObservationPositions;
    if ~isempty(allObservationPositions)
        consolidatedVictim.lastObservationPosition = ...
            allObservationPositions(end,:);
    end

    consolidatedVictims(end+1,1) = ...
        consolidatedVictim; %#ok<AGROW>
end

[consolidatedVictims,finalPeaks, ...
        rescuedUnmatchedRecordMask, ...
        unmatchedRecordPeakLogOdds, ...
        unmatchedRecordPeakSupport] = ...
    rescueStrongUnmatchedRangedRecords( ...
        victims,assignments,consolidatedVictims, ...
        finalPeaks,rawConfirmedTracks, ...
        bayesianState,bayesianConfig);

victims = consolidatedVictims;
report.matchedRecordCount = nnz(assignments > 0);
report.unmatchedRecordCount = nnz( ...
    assignments == 0 & ...
    ~rescuedUnmatchedRecordMask);
report.consolidatedRecordCount = numel(victims);
report.recordToTrackIndex = assignments;
report.assignmentDistances = assignmentDistances;
report.assignmentGates = assignmentGates;
report.assignmentAnchorTrackID = assignmentAnchorTrackID;
report.usedUncertaintyRescue = usedUncertaintyRescue;
report.rescuedUnmatchedRecordMask = ...
    rescuedUnmatchedRecordMask;
report.rescuedUnmatchedRecordCount = ...
    nnz(rescuedUnmatchedRecordMask);
report.unmatchedRecordPeakLogOdds = ...
    unmatchedRecordPeakLogOdds;
report.unmatchedRecordPeakSupport = ...
    unmatchedRecordPeakSupport;

end


