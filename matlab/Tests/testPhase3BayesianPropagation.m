%% ============================================================
% Synthetic Scenario Fixture
%% ============================================================

function scenario = buildSyntheticScenario()

gridSize = [10 12];

[rowGrid, columnGrid] = ndgrid( ...
    1:gridSize(1), ...
    1:gridSize(2));

scenario = struct();

scenario.gridSize = gridSize;

scenario.environment = struct();

scenario.environment.debris = ...
    (rowGrid - 1) ./ ...
    max(gridSize(1) - 1, 1);

scenario.environment.attenuation = ...
    (columnGrid - 1) ./ ...
    max(gridSize(2) - 1, 1);

scenario.environment.noise = ...
    0.20 .* ones(gridSize);

scenario.environment.obstacles = ...
    false(gridSize);

scenario.environment.obstacles(4:7,6) = true;

scenario.environment.vitalSigns = ...
    zeros(gridSize);
% خريطة مخفية يجب ألا تستخدمها دالة الانتشار

scenario.victims = [4 5];

scenario.groundTruth = struct();

scenario.groundTruth.locations = [4 5];

end