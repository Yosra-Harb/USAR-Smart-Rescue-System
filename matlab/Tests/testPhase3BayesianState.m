%% ============================================================
% Test Default Initialization
%% ============================================================

function testDefaultInitialization(testCase)

gridSize = [50 50];

state = initializeBayesianLocalizationState(gridSize);

verifyEqual( ...
    testCase, ...
    state.gridSize, ...
    gridSize);

verifySize( ...
    testCase, ...
    state.logOddsMap, ...
    gridSize);

verifySize( ...
    testCase, ...
    state.probabilityMap, ...
    gridSize);

verifySize( ...
    testCase, ...
    state.observationCount, ...
    gridSize);

verifySize( ...
    testCase, ...
    state.weightedObservationSupport, ...
    gridSize);

end

%% ============================================================
% Test Sparse Default Prior
%% ============================================================

function testDefaultPriorRepresentsOneExpectedCell(testCase)

gridSize = [20 25];

state = initializeBayesianLocalizationState(gridSize);

expectedPrior = 1 / prod(gridSize);

verifyEqual( ...
    testCase, ...
    state.priorProbability, ...
    expectedPrior, ...
    'AbsTol', ...
    1e-12);

verifyEqual( ...
    testCase, ...
    state.probabilityMap, ...
    expectedPrior .* ones(gridSize), ...
    'AbsTol', ...
    1e-12);

end

%% ============================================================
% Test Custom Prior
%% ============================================================

function testCustomPriorIsApplied(testCase)

gridSize = [12 18];
customPrior = 0.02;

state = initializeBayesianLocalizationState( ...
    gridSize, ...
    customPrior);

expectedLogOdds = log( ...
    customPrior / ...
    (1 - customPrior));

verifyEqual( ...
    testCase, ...
    state.priorProbability, ...
    customPrior, ...
    'AbsTol', ...
    1e-12);

verifyEqual( ...
    testCase, ...
    state.logOddsMap, ...
    expectedLogOdds .* ones(gridSize), ...
    'AbsTol', ...
    1e-12);

end

%% ============================================================
% Test Empty Diagnostics
%% ============================================================

function testDiagnosticsStartEmpty(testCase)

