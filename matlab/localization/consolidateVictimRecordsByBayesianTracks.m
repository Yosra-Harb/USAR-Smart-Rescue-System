function [consolidatedVictims,finalPeaks,rescuedMask, ...
        recordPeakLogOdds,recordPeakSupport] = ...
    rescueStrongUnmatchedRangedRecords( ...
        inputVictims,assignments,consolidatedVictims, ...
        finalPeaks,rawConfirmedTracks,bayesianState,config)
% إنقاذ محافظ لسجل UWB قوي لم يستطع المتتبع تكوين مسار مؤكد له.
% لا يكفي السجل منفردًا: يلزم تعدد المشاهدات، وتكرار القياس المباشر،
% ودليل خريطة قوي، وانفصال عن جميع المسارات والكشوف المقبولة.

numberOfRecords = numel(inputVictims);
rescuedMask = false(numberOfRecords,1);
recordPeakLogOdds = -inf(numberOfRecords,1);
recordPeakSupport = zeros(numberOfRecords,1);

requiredConfigFields = { ...
    'unmatchedRangedRecordRescueMinimumViews', ...
    'unmatchedRangedRecordRescueMinimumAssociations', ...
    'unmatchedRangedRecordRescueMinimumLogOdds', ...
    'unmatchedRangedRecordRescueMinimumSupport', ...
    'unmatchedRangedRecordRescueMinimumSeparation', ...
    'unmatchedRangedRecordRescuePeakSearchRadius'};
requiredStateFields = {'logOddsMap','weightedObservationSupport'};

if isempty(inputVictims) || ...
        ~all(isfield(config,requiredConfigFields)) || ...
        ~all(isfield(bayesianState,requiredStateFields)) || ...
        isempty(bayesianState.logOddsMap) || ...
        ~isequal(size(bayesianState.logOddsMap), ...
            size(bayesianState.weightedObservationSupport))
    return;
end

rawTrackPositions = zeros(0,2);
if ~isempty(rawConfirmedTracks)
    rawTrackPositions = reshape( ...
        [rawConfirmedTracks.position],2,[])';
end

candidateIndices = zeros(0,1);
candidateScores = zeros(0,1);

for recordIndex = find(assignments == 0)'
    record = inputVictims(recordIndex);
    hasRangedEvidence = ...
        isfield(record,'hasRangedMeasurementEvidence') && ...
        logical(record.hasRangedMeasurementEvidence);
    rangedAssociationCount = 0;
    if isfield(record,'rangedMeasurementAssociationCount') && ...
            isfinite(record.rangedMeasurementAssociationCount)
        rangedAssociationCount = ...
            record.rangedMeasurementAssociationCount;
    end
    independentViewCount = 0;
    if isfield(record,'independentViewCount') && ...
            isfinite(record.independentViewCount)
        independentViewCount = record.independentViewCount;
    end

    if ~hasRangedEvidence || ...
            rangedAssociationCount < ...
                config.unmatchedRangedRecordRescueMinimumAssociations || ...
            independentViewCount < ...
                config.unmatchedRangedRecordRescueMinimumViews
        continue;
    end

    [peakPosition,peakLogOdds] = ...
        findStrongestLocalLogOddsPeak( ...
            bayesianState.logOddsMap, ...
            record.position(1:2), ...
            config.unmatchedRangedRecordRescuePeakSearchRadius);
    peakSupport = bayesianState.weightedObservationSupport( ...
        peakPosition(1),peakPosition(2));
    recordPeakLogOdds(recordIndex) = peakLogOdds;
    recordPeakSupport(recordIndex) = peakSupport;

    if ~isfinite(peakLogOdds) || ...
            ~isfinite(peakSupport) || ...
            peakLogOdds < ...
            config.unmatchedRangedRecordRescueMinimumLogOdds || ...
            peakSupport < ...
            config.unmatchedRangedRecordRescueMinimumSupport
        continue;
    end

    if ~isempty(rawTrackPositions)
        trackDistances = hypot( ...
            rawTrackPositions(:,1)-record.position(1), ...
            rawTrackPositions(:,2)-record.position(2));
        if any(trackDistances < ...
                config.unmatchedRangedRecordRescueMinimumSeparation)
            continue;
        end
    end

    candidateIndices(end+1,1) = recordIndex; %#ok<AGROW>
    candidateScores(end+1,1) = ... %#ok<AGROW>
        peakLogOdds + log1p(max(0,peakSupport)) + ...
        0.05*independentViewCount + ...
        0.01*rangedAssociationCount;
end

if isempty(candidateIndices)
    return;
end

[~,candidateOrder] = sort(candidateScores,'descend');
candidateIndices = candidateIndices(candidateOrder);
acceptedPositions = zeros(0,2);
if ~isempty(consolidatedVictims)
    acceptedPositions = reshape( ...
        [consolidatedVictims.position],2,[])';
end

for candidateOffset = 1:numel(candidateIndices)
    recordIndex = candidateIndices(candidateOffset);
    record = inputVictims(recordIndex);
    recordPosition = double(record.position(1:2));

    if ~isempty(acceptedPositions)
        acceptedDistances = hypot( ...
            acceptedPositions(:,1)-recordPosition(1), ...
            acceptedPositions(:,2)-recordPosition(2));
        if any(acceptedDistances < ...
                config.unmatchedRangedRecordRescueMinimumSeparation)
            continue;
        end
    end

    record.position = round(recordPosition);
    consolidatedVictims(end+1,1) = record; %#ok<AGROW>
    acceptedPositions(end+1,:) = recordPosition; %#ok<AGROW>
    rescuedMask(recordIndex) = true;

    probability = 1/(1+exp( ...
        -recordPeakLogOdds(recordIndex)));
    finalPeaks(end+1,1) = struct( ... %#ok<AGROW>
        'row',record.position(1), ...
        'column',record.position(2), ...
        'value',probability, ...
        'prominence',recordPeakLogOdds(recordIndex), ...
        'selectionScore',probability, ...
        'probability',probability, ...
        'uncertaintyRadius',1.0);
end

