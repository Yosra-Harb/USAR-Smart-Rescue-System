function [mergedTracks, finalRawClusterIndex, ...
        finalClusterDiameters, diagnostics] = ...
    consolidateTrackClustersByLogOddsBasins( ...
        rawTracks, ...
        preBasinMergedTracks, ...
        rawPreBasinClusterIndex, ...
        logOddsMap, ...
        weightedSupportMap, ...
        maximumValleyDrop, ...
        maximumPeakDistance, ...
        peakSearchRadius, ...
        minimumPeakLogOdds, ...
        lineSamplesPerCell, ...
        minimumSupportRetention, ...
        weakMinimumLogOddsGap, ...
        weakMaximumRelativeSupport, ...
        weakMaximumRawTracks, ...
        weakMapMinimumLogOddsGap, ...
        weakMapMaximumRelativeSupport, ...
        weakMapMaximumRawTracks, ...
        minimumIndependentViewDistance, ...
        minimumResolvedRangedViews, ...
        resolvedSourceMinimumSeparation, ...
        resolvedSourceSoftPeakSeparation, ...
        resolvedSourceMaximumBridgeRetention)
% يدمج فقط العناقيد التي تقع جميع أزواج قممها داخل حوض Log-Odds
% واحد. قاعدة complete-link تمنع سلسلة من العلاقات المحلية من
% دمج مجموعتين يفصل بينهما وادٍ قوي أو مسافة غير مسموحة.

numberOfPreBasinClusters = ...
    numel(preBasinMergedTracks);
diagnostics = createEmptyBasinDiagnostics( ...
    numberOfPreBasinClusters);
mergedTracks = preBasinMergedTracks;
finalRawClusterIndex = rawPreBasinClusterIndex;
finalClusterDiameters = zeros( ...
    numberOfPreBasinClusters,1);

for clusterIndex = 1:numberOfPreBasinClusters
    groupPositions = reshape( ...
        [rawTracks( ...
        rawPreBasinClusterIndex == clusterIndex).position], ...
        2,[])';
    finalClusterDiameters(clusterIndex) = ...
        calculatePositionDiameter(groupPositions);
end

clusterUpdateSteps = cell(numberOfPreBasinClusters,1);

for clusterIndex = 1:numberOfPreBasinClusters
    clusterMembers = rawTracks( ...
        rawPreBasinClusterIndex == clusterIndex);
    updateSteps = zeros(0,1);

    for memberIndex = 1:numel(clusterMembers)
        if isfield(clusterMembers, 'updateStepHistory') && ...
                ~isempty(clusterMembers(memberIndex).updateStepHistory)
            updateSteps = [ ...
                updateSteps; ...
                clusterMembers(memberIndex).updateStepHistory(:)]; ...
                %#ok<AGROW>
        elseif isfield(clusterMembers, 'lastUpdateStep') && ...
                ~isempty(clusterMembers(memberIndex).lastUpdateStep)
            updateSteps(end+1,1) = ... %#ok<AGROW>
                clusterMembers(memberIndex).lastUpdateStep;
        end
    end

    clusterUpdateSteps{clusterIndex} = unique(updateSteps);
    diagnostics.independentRangedViewCounts(clusterIndex) = ...
        max([clusterMembers.independentRangedViewCount]);
end

if isempty(logOddsMap) || ...
        ~isequal(size(logOddsMap), ...
        size(weightedSupportMap))
    return;
end

for clusterIndex = 1:numberOfPreBasinClusters
    [peakPosition,peakValue] = ...
        findStrongestLocalLogOddsPeak( ...
            logOddsMap, ...
            preBasinMergedTracks(clusterIndex).position, ...
            peakSearchRadius);
    diagnostics.peakPositions(clusterIndex,:) = ...
        peakPosition;
    diagnostics.peakLogOdds(clusterIndex) = ...
        peakValue;
    diagnostics.peakSupport(clusterIndex) = ...
        weightedSupportMap( ...
            peakPosition(1),peakPosition(2));
end


if numberOfPreBasinClusters < 2 || ...
        maximumValleyDrop < 0
    return;
end

for firstCluster = 1:numberOfPreBasinClusters
    for secondCluster = ...
            firstCluster+1:numberOfPreBasinClusters
        firstPeakPosition = ...
            diagnostics.peakPositions(firstCluster,:);
        secondPeakPosition = ...
            diagnostics.peakPositions(secondCluster,:);
        peakDistance = norm( ...
            firstPeakPosition-secondPeakPosition);
        valleyDrop = calculateLogOddsValleyDrop( ...
            logOddsMap, ...
            firstPeakPosition, ...
            secondPeakPosition, ...
            diagnostics.peakLogOdds(firstCluster), ...
            diagnostics.peakLogOdds(secondCluster), ...
            lineSamplesPerCell);
        supportRetention = ...
            calculateSupportRetention( ...
                weightedSupportMap, ...
                firstPeakPosition, ...
                secondPeakPosition, ...
                diagnostics.peakSupport(firstCluster), ...
                diagnostics.peakSupport(secondCluster), ...
                lineSamplesPerCell);
        hasResolvedRangedEvidence = ...
            diagnostics.independentRangedViewCounts( ...
                firstCluster) >= minimumResolvedRangedViews && ...
            diagnostics.independentRangedViewCounts( ...
                secondCluster) >= minimumResolvedRangedViews;
        hasHardPeakSeparation = ...
            peakDistance >= resolvedSourceMinimumSeparation;
        hasSoftPeakSeparationWithSupportValley = ...
            peakDistance >= resolvedSourceSoftPeakSeparation && ...
            supportRetention <= ...
                resolvedSourceMaximumBridgeRetention;
        measurementResolvedVeto = ...
            hasResolvedRangedEvidence && ...
            (hasHardPeakSeparation || ...
             hasSoftPeakSeparationWithSupportValley);
        firstUpdateSteps = ...
            clusterUpdateSteps{firstCluster};
        secondUpdateSteps = ...
            clusterUpdateSteps{secondCluster};
        sharedUpdateStepCount = numel(intersect( ...
            firstUpdateSteps,secondUpdateSteps));
        minimumUpdateStepCount = min( ...
            numel(firstUpdateSteps), ...
            numel(secondUpdateSteps));
        unionUpdateStepCount = numel(union( ...
            firstUpdateSteps,secondUpdateSteps));

        if minimumUpdateStepCount > 0
            temporalContainment = ...
                sharedUpdateStepCount / ...
                minimumUpdateStepCount;
        else
            temporalContainment = 0;
        end

        if unionUpdateStepCount > 0
            temporalJaccard = ...
                sharedUpdateStepCount / ...
                unionUpdateStepCount;
        else
            temporalJaccard = 0;
        end
        diagnostics.pairwisePeakDistances( ...
            firstCluster,secondCluster) = peakDistance;
        diagnostics.pairwisePeakDistances( ...
            secondCluster,firstCluster) = peakDistance;
        diagnostics.pairwiseValleyDrops( ...
            firstCluster,secondCluster) = valleyDrop;
        diagnostics.pairwiseValleyDrops( ...
            secondCluster,firstCluster) = valleyDrop;
        diagnostics.pairwiseSupportRetention( ...
            firstCluster,secondCluster) = ...
            supportRetention;
        diagnostics.pairwiseSupportRetention( ...
            secondCluster,firstCluster) = ...
            supportRetention;
        diagnostics.pairwiseTemporalContainment( ...
            firstCluster,secondCluster) = ...
            temporalContainment;
        diagnostics.pairwiseTemporalContainment( ...
            secondCluster,firstCluster) = ...
            temporalContainment;
        diagnostics.pairwiseTemporalJaccard( ...
            firstCluster,secondCluster) = ...
            temporalJaccard;
        diagnostics.pairwiseTemporalJaccard( ...
            secondCluster,firstCluster) = ...
            temporalJaccard;
        diagnostics.pairwiseMeasurementResolvedVeto( ...
            firstCluster,secondCluster) = ...
            measurementResolvedVeto;
        diagnostics.pairwiseMeasurementResolvedVeto( ...
            secondCluster,firstCluster) = ...
            measurementResolvedVeto;
    end
end

groupIndex = (1:numberOfPreBasinClusters)';

while true
    groupIDs = unique(groupIndex, 'stable');
    bestFirstGroupID = 0;
    bestSecondGroupID = 0;
    bestMaximumValleyDrop = inf;
    bestMaximumPeakDistance = inf;

    for firstOffset = 1:numel(groupIDs)
        firstGroupID = groupIDs(firstOffset);
        firstMembers = find( ...
            groupIndex == firstGroupID);

        for secondOffset = ...
                firstOffset+1:numel(groupIDs)
            secondGroupID = groupIDs(secondOffset);
            secondMembers = find( ...
                groupIndex == secondGroupID);
            crossValleyDrops = ...
                diagnostics.pairwiseValleyDrops( ...
                    firstMembers,secondMembers);
            crossPeakDistances = ...
                diagnostics.pairwisePeakDistances( ...
                    firstMembers,secondMembers);
            crossSupportRetention = ...
                diagnostics.pairwiseSupportRetention( ...
                    firstMembers,secondMembers);
            crossMeasurementResolvedVeto = ...
                diagnostics.pairwiseMeasurementResolvedVeto( ...
                    firstMembers,secondMembers);
            allMembers = [ ...
                firstMembers; secondMembers];
            peaksAreStrong = all( ...
                diagnostics.peakLogOdds(allMembers) >= ...
                minimumPeakLogOdds);
            groupsShareOneBasin = ...
                peaksAreStrong && ...
                all(crossValleyDrops(:) <= ...
                    maximumValleyDrop) && ...
                all(crossPeakDistances(:) <= ...
                    maximumPeakDistance) && ...
                all(crossSupportRetention(:) >= ...
                    minimumSupportRetention) && ...
                ~any(crossMeasurementResolvedVeto(:));

            if ~groupsShareOneBasin
                continue;
            end

            candidateMaximumValleyDrop = ...
                max(crossValleyDrops(:));
            candidateMaximumPeakDistance = ...
                max(crossPeakDistances(:));
            isBetterCandidate = ...
                candidateMaximumValleyDrop < ...
                    bestMaximumValleyDrop || ...
                (candidateMaximumValleyDrop == ...
                    bestMaximumValleyDrop && ...
                candidateMaximumPeakDistance < ...
                    bestMaximumPeakDistance);

            if isBetterCandidate
                bestFirstGroupID = firstGroupID;
                bestSecondGroupID = secondGroupID;
                bestMaximumValleyDrop = ...
                    candidateMaximumValleyDrop;
                bestMaximumPeakDistance = ...
                    candidateMaximumPeakDistance;
            end
        end
    end

    if bestFirstGroupID == 0
        break;
    end

    groupIndex(groupIndex == bestSecondGroupID) = ...
        bestFirstGroupID;
end

groupIDs = unique(groupIndex, 'stable');
provisionalPreToFinalClusterIndex = ...
    zeros(size(groupIndex));

for provisionalCluster = 1:numel(groupIDs)
    provisionalPreToFinalClusterIndex( ...
        groupIndex == groupIDs(provisionalCluster)) = ...
        provisionalCluster;
end

% تصفية مشتركة شديدة المحافظة للحوض المنفرد الضعيف. لا تكفي
% أي إشارة منفردة: يجب أن يدعمه مسار خام واحد فقط، وأن يكون فرق
% Log-Odds كبيرًا، وأن يكون دعمه النسبي منخفضًا، مع وجود حوض آخر.
numberOfProvisionalClusters = numel(groupIDs);
rawProvisionalClusterIndex = ...
    provisionalPreToFinalClusterIndex( ...
        rawPreBasinClusterIndex);
provisionalPeakLogOdds = ...
    -inf(numberOfProvisionalClusters,1);
provisionalPeakSupport = ...
    zeros(numberOfProvisionalClusters,1);
provisionalRawTrackCounts = ...
    zeros(numberOfProvisionalClusters,1);
provisionalMeasurementResolved = ...
    false(numberOfProvisionalClusters,1);

for provisionalCluster = ...
        1:numberOfProvisionalClusters
    preMembers = find( ...
        provisionalPreToFinalClusterIndex == ...
        provisionalCluster);
    provisionalPeakLogOdds(provisionalCluster) = ...
        max(diagnostics.peakLogOdds(preMembers));
    provisionalPeakSupport(provisionalCluster) = ...
        max(diagnostics.peakSupport(preMembers));
    provisionalRawTrackCounts(provisionalCluster) = ...
        nnz(rawProvisionalClusterIndex == ...
        provisionalCluster);
    provisionalMeasurementResolved(provisionalCluster) = ...
        any(diagnostics.independentRangedViewCounts( ...
            preMembers) >= minimumResolvedRangedViews);
end

rejectedProvisionalClusterMask = ...
    false(numberOfProvisionalClusters,1);

if numberOfProvisionalClusters > 1
    strongestPeakLogOdds = ...
        max(provisionalPeakLogOdds);
    strongestPeakSupport = ...
        max(provisionalPeakSupport);

    for provisionalCluster = ...
            1:numberOfProvisionalClusters
        logOddsGap = strongestPeakLogOdds - ...
            provisionalPeakLogOdds(provisionalCluster);
        relativeSupport = ...
            provisionalPeakSupport(provisionalCluster) / ...
            max(strongestPeakSupport,eps);
        isWeakSingleton = ...
            provisionalRawTrackCounts( ...
                provisionalCluster) <= ...
                weakMaximumRawTracks && ...
            logOddsGap >= weakMinimumLogOddsGap && ...
            relativeSupport <= ...
                weakMaximumRelativeSupport;
        isWeakMapOnlyPair = ...
            provisionalRawTrackCounts( ...
                provisionalCluster) <= ...
                weakMapMaximumRawTracks && ...
            logOddsGap >= weakMapMinimumLogOddsGap && ...
            relativeSupport <= ...
                weakMapMaximumRelativeSupport;
        rejectedProvisionalClusterMask( ...
            provisionalCluster) = ...
            ~provisionalMeasurementResolved( ...
                provisionalCluster) && ...
            (isWeakSingleton || isWeakMapOnlyPair);
    end
end

preToFinalClusterIndex = zeros(size(groupIndex));
acceptedProvisionalClusters = find( ...
    ~rejectedProvisionalClusterMask);

for finalCluster = ...
        1:numel(acceptedProvisionalClusters)
    provisionalCluster = ...
        acceptedProvisionalClusters(finalCluster);
    preToFinalClusterIndex( ...
        provisionalPreToFinalClusterIndex == ...
        provisionalCluster) = finalCluster;
end

diagnostics.preToFinalClusterIndex = ...
    preToFinalClusterIndex;
diagnostics.mergedClusterCount = ...
    numberOfPreBasinClusters-numel(groupIDs);
diagnostics.rejectedPreClusterMask = ...
    rejectedProvisionalClusterMask( ...
        provisionalPreToFinalClusterIndex);
diagnostics.rejectedClusterCount = ...
    nnz(rejectedProvisionalClusterMask);
finalRawClusterIndex = ...
    preToFinalClusterIndex( ...
        rawPreBasinClusterIndex);
mergedTracks = rawTracks([]);
numberOfFinalClusters = ...
    numel(acceptedProvisionalClusters);
finalClusterDiameters = zeros( ...
    numberOfFinalClusters,1);

for finalCluster = 1:numberOfFinalClusters
    group = rawTracks( ...
        finalRawClusterIndex == finalCluster);
    groupPositions = reshape( ...
        [group.position],2,[])';
    finalClusterDiameters(finalCluster) = ...
        calculatePositionDiameter(groupPositions);
    mergedTracks(end+1,1) = mergeTrackGroup( ... %#ok<AGROW>
        group,minimumIndependentViewDistance);
end

end


function [peakPosition,peakValue] = ...
    findStrongestLocalLogOddsPeak( ...
        logOddsMap,trackPosition,searchRadius)

centerRow = min(max( ...
    1,round(trackPosition(1))), ...
    size(logOddsMap,1));
centerColumn = min(max( ...
    1,round(trackPosition(2))), ...
    size(logOddsMap,2));
minimumRow = max(1,centerRow-searchRadius);
maximumRow = min( ...
    size(logOddsMap,1),centerRow+searchRadius);
minimumColumn = max(1,centerColumn-searchRadius);
maximumColumn = min( ...
    size(logOddsMap,2),centerColumn+searchRadius);
localMap = logOddsMap( ...
    minimumRow:maximumRow, ...
    minimumColumn:maximumColumn);
[peakValue,localIndex] = max(localMap(:));
[localRow,localColumn] = ...
    ind2sub(size(localMap),localIndex);
peakPosition = [ ...
    minimumRow+localRow-1, ...
    minimumColumn+localColumn-1];

end


function valleyDrop = calculateLogOddsValleyDrop( ...
    logOddsMap,firstPeakPosition,secondPeakPosition, ...
    firstPeakValue,secondPeakValue,lineSamplesPerCell)

peakDistance = norm( ...
    firstPeakPosition-secondPeakPosition);
sampleCount = max( ...
    3,ceil(peakDistance*lineSamplesPerCell)+1);
sampleRows = linspace( ...
    firstPeakPosition(1), ...
    secondPeakPosition(1), ...
    sampleCount);
sampleColumns = linspace( ...
    firstPeakPosition(2), ...
    secondPeakPosition(2), ...
    sampleCount);
lineLogOdds = interp2( ...
    logOddsMap,sampleColumns,sampleRows,'linear');

if any(~isfinite(lineLogOdds))
    valleyDrop = inf;
    return;
end

lowerPeakValue = min( ...
    firstPeakValue,secondPeakValue);
valleyDrop = max( ...
    0,lowerPeakValue-min(lineLogOdds));

end


function retention = calculateSupportRetention( ...
    supportMap,firstPeakPosition,secondPeakPosition, ...
    firstPeakSupport,secondPeakSupport,lineSamplesPerCell)

peakDistance = norm( ...
    firstPeakPosition-secondPeakPosition);
sampleCount = max( ...
    3,ceil(peakDistance*lineSamplesPerCell)+1);
sampleRows = linspace( ...
    firstPeakPosition(1), ...
    secondPeakPosition(1), ...
    sampleCount);
sampleColumns = linspace( ...
    firstPeakPosition(2), ...
    secondPeakPosition(2), ...
    sampleCount);
lineSupport = interp2( ...
    supportMap,sampleColumns,sampleRows,'linear');

if any(~isfinite(lineSupport))
    retention = 0;
    return;
end

lowerPeakSupport = min( ...
    firstPeakSupport,secondPeakSupport);

if lowerPeakSupport <= eps
    retention = 0;
    return;
end

retention = min( ...
    1,max(0,min(lineSupport) / ...
    lowerPeakSupport));

end


function diameter = calculatePositionDiameter(positions)

if size(positions,1) < 2
    diameter = 0;
    return;
end

rowOffsets = positions(:,1) - positions(:,1)';
columnOffsets = positions(:,2) - positions(:,2)';
distances = hypot(rowOffsets, columnOffsets);
diameter = max(distances(:));

end


function distance = calculateTrackMahalanobisDistance( ...
    firstTrack, ...
    secondTrack)

positionOffset = ...
    firstTrack.position(1:2)' - ...
    secondTrack.position(1:2)';
combinedCovariance = ...
    firstTrack.covariance + ...
    secondTrack.covariance;

if ~isequal(size(combinedCovariance), [2 2]) || ...
        any(~isfinite(combinedCovariance), 'all')
    distance = inf;
    return;
end

combinedCovariance = ...
    0.5 * (combinedCovariance + combinedCovariance');
combinedCovariance = ...
    combinedCovariance + 1e-9 * eye(2);

squaredDistance = ...
    positionOffset' * ...
    pinv(combinedCovariance) * ...
    positionOffset;
distance = sqrt(max(0, squaredDistance));

end


function mergedTrack = mergeTrackGroup( ...
    tracks, minimumIndependentViewDistance)

if numel(tracks) == 1
    mergedTrack = tracks;
    return;
end

existenceProbabilities = ...
    [tracks.existenceProbability]';
independentViewCounts = ...
    [tracks.independentViewCount]';
weights = max(eps, existenceProbabilities) .* ...
    max(1, independentViewCounts);
positions = reshape([tracks.position], 2, [])';
mergedPosition = sum(positions .* weights, 1) ./ ...
    sum(weights);

mergedCovariance = zeros(2,2);
for index = 1:numel(tracks)
    offset = positions(index,:) - mergedPosition;
    mergedCovariance = mergedCovariance + ...
        weights(index) .* ( ...
            tracks(index).covariance + ...
            offset(:) * offset(:)');
end
mergedCovariance = mergedCovariance ./ sum(weights);

[~, baseIndex] = max(independentViewCounts);
mergedTrack = tracks(baseIndex);
mergedTrack.id = min([tracks.id]);
mergedTrack.position = mergedPosition;
mergedTrack.existenceProbability = ...
    max(existenceProbabilities);
mergedTrack.covariance = mergedCovariance;
mergedTrack.updateCount = max([tracks.updateCount]);
mergedTrack.maximumProbability = ...
    max([tracks.maximumProbability]);
mergedTrack.missedUpdateCount = ...
    min([tracks.missedUpdateCount]);
mergedTrack.lastUpdateStep = ...
    max([tracks.lastUpdateStep]);
mergedUpdateSteps = zeros(0,1);

for trackIndex = 1:numel(tracks)
    if isfield(tracks, 'updateStepHistory') && ...
            ~isempty(tracks(trackIndex).updateStepHistory)
        mergedUpdateSteps = [ ...
            mergedUpdateSteps; ...
            tracks(trackIndex).updateStepHistory(:)]; ...
            %#ok<AGROW>
    elseif ~isempty(tracks(trackIndex).lastUpdateStep)
        mergedUpdateSteps(end+1,1) = ... %#ok<AGROW>
            tracks(trackIndex).lastUpdateStep;
    end
end

mergedTrack.updateStepHistory = ...
    unique(mergedUpdateSteps);
mergedTrack.rangedMeasurementUpdateCount = ...
    max([tracks.rangedMeasurementUpdateCount]);

mergedObservations = ...
    tracks(baseIndex).observationPositions(:,1:2);
for trackIndex = 1:numel(tracks)
    observations = tracks(trackIndex).observationPositions;
    for observationIndex = 1:size(observations,1)
        candidate = observations(observationIndex,1:2);
        if isempty(mergedObservations)
            mergedObservations = candidate;
        else
            distances = hypot( ...
                mergedObservations(:,1) - candidate(1), ...
                mergedObservations(:,2) - candidate(2));
            if all(distances >= minimumIndependentViewDistance)
                mergedObservations(end+1,:) = ... %#ok<AGROW>
                    candidate;
            end
        end
    end
end

mergedTrack.observationPositions = mergedObservations;
mergedTrack.independentViewCount = ...
    size(mergedObservations,1);

mergedRangedObservations = zeros(0,2);
for trackIndex = 1:numel(tracks)
    rangedObservations = ...
        tracks(trackIndex).rangedObservationPositions;
    for observationIndex = 1:size(rangedObservations,1)
        candidate = rangedObservations(observationIndex,1:2);
        if isempty(mergedRangedObservations)
            mergedRangedObservations = candidate;
        else
            distances = hypot( ...
                mergedRangedObservations(:,1)-candidate(1), ...
                mergedRangedObservations(:,2)-candidate(2));
            if all(distances >= minimumIndependentViewDistance)
                mergedRangedObservations(end+1,:) = ... %#ok<AGROW>
                    candidate;
            end
        end
    end
end

mergedTrack.rangedObservationPositions = ...
    mergedRangedObservations;
mergedTrack.independentRangedViewCount = ...
    size(mergedRangedObservations,1);
mergedTrack.status = "CONFIRMED";

end


function tracks = normalizeMeasurementResolvedTrackSchema(tracks)

for trackIndex = 1:numel(tracks)
    if ~isfield(tracks,'rangedMeasurementUpdateCount') || ...
            isempty(tracks(trackIndex).rangedMeasurementUpdateCount)
        tracks(trackIndex).rangedMeasurementUpdateCount = 0;
    end
    if ~isfield(tracks,'independentRangedViewCount') || ...
            isempty(tracks(trackIndex).independentRangedViewCount)
        tracks(trackIndex).independentRangedViewCount = 0;
    end
    if ~isfield(tracks,'rangedObservationPositions') || ...
            isempty(tracks(trackIndex).rangedObservationPositions)
        tracks(trackIndex).rangedObservationPositions = zeros(0,2);
    end
end

