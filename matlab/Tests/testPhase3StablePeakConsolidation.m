function state = createPeakState( ...
    peakPositions, ...
    peakValues, ...
    gridSize)

state = struct();

state.evidenceMap = zeros( ...
    gridSize(1), ...
    gridSize(2));

state.observationCount = zeros( ...
    gridSize(1), ...
    gridSize(2));

state.weightSum = zeros( ...
    gridSize(1), ...
    gridSize(2));

for peakIndex = 1:size(peakPositions,1)

    peakRow = peakPositions(peakIndex,1);
    peakColumn = peakPositions(peakIndex,2);

    state.evidenceMap( ...
        peakRow, ...
        peakColumn) = ...
        peakValues(peakIndex);

    state.observationCount( ...
        peakRow, ...
        peakColumn) = 5;

    state.weightSum( ...
        peakRow, ...
        peakColumn) = 5;

end

end


function victims = createEmptyVictimArray()

template = createVictim( ...
    1, ...
    [1 1], ...
    [1 1]);

victims = repmat(template, 0, 1);

end


function victim = createVictim( ...
    victimID, ...
    position, ...
    observationPositions)

currentTime = datetime("now");

independentCount = ...
    size(observationPositions,1);

priorityScore = ...
    0.40 + 0.01 * victimID;

victim = struct( ...
    'id', victimID, ...
    'position', position, ...
    'vitalityIndex', 0.50, ...
    'priorityScore', priorityScore, ...
    'priorityLevel', ...
        classifyPriority(priorityScore), ...
    'firstDetectionTime', currentTime, ...
    'lastUpdateTime', currentTime, ...
    'detectionCount', independentCount, ...
    'independentViewCount', independentCount, ...
    'rawAssociationCount', independentCount, ...
    'observationPositions', observationPositions, ...
    'lastObservationPosition', ...
        observationPositions(end,:));

end
