function diagnostics = runTemporalCoexistenceDiagnostic()
%% ============================================================
% يشغّل حالات المعايرة والتحقق المطلوبة لقياس تعايش عناقيد
% المسارات زمنيًا. هذه الدالة تشخيصية ولا تغيّر قرارات الكشف.
%% ============================================================

scenarioTypes = [ ...
    "Ideal"; ...
    "MultipleVictims"; ...
    "MultipleVictims"; ...
    "MultipleVictims"];
seeds = [4; 3; 1003; 1005];

diagnostics = repmat(struct( ...
    'scenarioType', "", ...
    'seed', 0, ...
    'metrics', zeros(1,6), ...
    'preToFinalClusterIndex', zeros(0,1), ...
    'temporalContainment', zeros(0,0), ...
    'temporalJaccard', zeros(0,0)), ...
    0,1);

for caseIndex = 1:numel(seeds)
    scenarioType = scenarioTypes(caseIndex);
    seed = seeds(caseIndex);
    [result,probe] = runSingleScenarioEvaluation( ...
        scenarioType,seed);
    state = ...
        probe.memory.bayesianLocalizationState;
    report = state.consolidationReport;
    metrics = [ ...
        result.systemDetections, ...
        result.truePositives, ...
        result.falsePositives, ...
        result.falseNegatives, ...
        result.f1Score, ...
        result.localizationMeanError];

    diagnostics(end+1,1) = struct( ... %#ok<AGROW>
        'scenarioType', scenarioType, ...
        'seed', seed, ...
        'metrics', metrics, ...
        'preToFinalClusterIndex', ...
            report.basinPreToFinalClusterIndex, ...
        'temporalContainment', ...
            report.basinPairwiseTemporalContainment, ...
        'temporalJaccard', ...
            report.basinPairwiseTemporalJaccard);

    disp("================================")
    disp("SCENARIO:")
    disp(scenarioType)
    disp("SEED:")
    disp(seed)
    disp("METRICS:")
    disp(metrics)
    disp("PRE-TO-FINAL:")
    disp(report.basinPreToFinalClusterIndex)
    disp("TEMPORAL CONTAINMENT:")
    disp(round( ...
        report.basinPairwiseTemporalContainment,3))
    disp("TEMPORAL JACCARD:")
    disp(round( ...
        report.basinPairwiseTemporalJaccard,3))
end

end
