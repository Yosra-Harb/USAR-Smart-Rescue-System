function testSevenRecordsBecomeThreeVictims(testCase)

peakPositions = [ ...
    8 8;
    8 20;
    20 14];

state = createPeakState( ...
    peakPositions, ...
    [0.80; 0.70; 0.60], ...
    [32 32]);

victims = createEmptyVictimArray();

victims(end+1,1) = createVictim( ...
    1, [7 8], [2 2; 4 2]);

victims(end+1,1) = createVictim( ...
    2, [9 8], [2 2; 6 2]);

victims(end+1,1) = createVictim( ...
    3, [8 19], [2 15; 4 15]);

victims(end+1,1) = createVictim( ...
    4, [8 21], [2 17; 4 17]);

victims(end+1,1) = createVictim( ...
    5, [6 20], [6 17; 6 19]);

victims(end+1,1) = createVictim( ...
    6, [19 14], [17 12; 19 12]);

victims(end+1,1) = createVictim( ...
    7, [21 14], [21 12; 23 12]);

[consolidated, stablePeaks, report] = ...
    consolidateVictimRecordsByStablePeaks( ...
        victims, ...
        state);

verifyEqual(testCase, numel(stablePeaks), 3);
verifyEqual(testCase, numel(consolidated), 3);
verifyEqual(testCase, report.inputRecordCount, 7);
verifyEqual(testCase, report.matchedRecordCount, 7);
verifyEqual(testCase, report.unmatchedRecordCount, 0);

actualPositions = reshape( ...
    [consolidated.position], ...
    2, ...
    [])';

verifyEqual( ...
    testCase, ...
    sortrows(actualPositions), ...
    sortrows(peakPositions));

end


function testUnmatchedRecordIsPreserved(testCase)

state = createPeakState( ...
    [10 10], ...
    0.80, ...
    [40 40]);

victims = createEmptyVictimArray();

victims(end+1,1) = createVictim( ...
    1, [10 11], [8 8; 10 8]);

victims(end+1,1) = createVictim( ...
    2, [30 30], [28 28; 30 28]);

[consolidated, stablePeaks, report] = ...
    consolidateVictimRecordsByStablePeaks( ...
        victims, ...
        state);

verifyEqual(testCase, numel(stablePeaks), 1);
verifyEqual(testCase, numel(consolidated), 2);
verifyEqual(testCase, report.matchedRecordCount, 1);
verifyEqual(testCase, report.unmatchedRecordCount, 1);

actualPositions = reshape( ...
    [consolidated.position], ...
    2, ...
    [])';

verifyTrue( ...
    testCase, ...
    ismember([10 10], actualPositions, 'rows'));

verifyTrue( ...
    testCase, ...
    ismember([30 30], actualPositions, 'rows'));

end


