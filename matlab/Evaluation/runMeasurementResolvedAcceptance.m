function acceptance = runMeasurementResolvedAcceptance()
%% ============================================================
% بوابة قبول واحدة للإصدار v4.1.4.
%
% 1) جميع اختبارات الوحدات.
% 2) حالات الانحدار الصعبة المعروفة.
% 3) 60 تشغيلًا جديدًا ببذور لم تدخل في المعايرة السابقة.
%
% لا تشغّل FinalTest 2001:2005 ولا تستخدم Ground Truth في الكشف؛
% الحقيقة المرجعية تدخل هنا في حساب المقاييس بعد انتهاء كل مهمة فقط.
%% ============================================================

disp("================================")
disp("V4.1.4 EMPTY-SCHEMA FIELD-ORDER ACCEPTANCE")
disp("================================")

allResults = runAllTests();
testPassed = all([allResults.Passed]) && ...
    ~any([allResults.Failed]) && ...
    ~any([allResults.Incomplete]);

disp("UNIT TEST SUMMARY:")
disp("Passed=" + string(nnz([allResults.Passed])) + ...
    " | Failed=" + string(nnz([allResults.Failed])) + ...
    " | Incomplete=" + string(nnz([allResults.Incomplete])))

if ~testPassed
    error( ...
        "runMeasurementResolvedAcceptance:UnitTestsFailed", ...
        "Acceptance stopped because unit tests did not all pass.");
end

targetScenarios = [ ...
    "Ideal"; "Ideal"; "Ideal"; "HighNoise"; ...
    "DeepBurial"; ...
    "MultipleVictims"; "MultipleVictims"; ...
    "MultipleVictims"; "MultipleVictims"; ...
    "MultipleVictims"; "MultipleVictims"; ...
    "MultipleVictims"];
targetSeeds = [2;4;1001;2;3;1;2;3;4;5;1003;1005];
targetResults = cell(numel(targetSeeds),1);

disp("TARGETED REGRESSION:")
for runIndex = 1:numel(targetSeeds)
    result = runSingleScenarioEvaluation( ...
        targetScenarios(runIndex),targetSeeds(runIndex));
    targetResults{runIndex} = result;
    displayRun(result);
end

targetSucceeded = cellfun( ...
    @(result) result.runSucceeded,targetResults);
targetFalsePositives = sum(cellfun( ...
    @(result) finiteOrZero(result.falsePositives), ...
    targetResults));
targetFalseNegatives = sum(cellfun( ...
    @(result) finiteOrZero(result.falseNegatives), ...
    targetResults));
targetPassed = all(targetSucceeded) && ...
    targetFalsePositives == 0 && ...
    targetFalseNegatives == 0;

scenarioTypes = [ ...
    "Ideal"; "DenseDebris"; "HighNoise"; ...
    "DeepBurial"; "MultipleVictims"; ...
    "WeakVitalSigns"];
freshSeeds = (4001:4010)';
freshResults = cell( ...
    numel(scenarioTypes)*numel(freshSeeds),1);
freshIndex = 0;

disp("================================")
disp("FRESH VALIDATION SEEDS 4001:4010:")
for scenarioIndex = 1:numel(scenarioTypes)
    for seedIndex = 1:numel(freshSeeds)
        freshIndex = freshIndex+1;
        result = runSingleScenarioEvaluation( ...
            scenarioTypes(scenarioIndex), ...
            freshSeeds(seedIndex));
        freshResults{freshIndex} = result;
        displayRun(result);
    end
end

freshSucceeded = cellfun( ...
    @(result) result.runSucceeded,freshResults);
totalTruePositives = sum(cellfun( ...
    @(result) finiteOrZero(result.truePositives), ...
    freshResults));
totalFalsePositives = sum(cellfun( ...
    @(result) finiteOrZero(result.falsePositives), ...
    freshResults));
totalFalseNegatives = sum(cellfun( ...
    @(result) finiteOrZero(result.falseNegatives), ...
    freshResults));
precision = totalTruePositives / max( ...
    1,totalTruePositives+totalFalsePositives);
recall = totalTruePositives / max( ...
    1,totalTruePositives+totalFalseNegatives);
microF1 = 2*precision*recall / ...
    max(eps,precision+recall);
localizationErrors = cellfun( ...
    @(result) result.localizationMeanError, ...
    freshResults);
meanLocalizationError = mean( ...
    localizationErrors(isfinite(localizationErrors)));

freshScenarioNames = string(cellfun( ...
    @(result) char(string(result.scenarioType)), ...
    freshResults, ...
    'UniformOutput',false));
multipleMask = freshScenarioNames == "MultipleVictims";
multipleResults = freshResults(multipleMask);
multipleTruePositives = sum(cellfun( ...
    @(result) finiteOrZero(result.truePositives), ...
    multipleResults));
multipleFalsePositives = sum(cellfun( ...
    @(result) finiteOrZero(result.falsePositives), ...
    multipleResults));
multipleFalseNegatives = sum(cellfun( ...
    @(result) finiteOrZero(result.falseNegatives), ...
    multipleResults));
multiplePrecision = multipleTruePositives / max( ...
    1,multipleTruePositives+multipleFalsePositives);
multipleRecall = multipleTruePositives / max( ...
    1,multipleTruePositives+multipleFalseNegatives);

freshPassed = all(freshSucceeded) && ...
    precision >= 0.98 && ...
    recall >= 0.98 && ...
    multiplePrecision >= 0.98 && ...
    multipleRecall >= 0.96 && ...
    meanLocalizationError <= 2.50;

acceptance = struct();
acceptance.version = "4.1.4";
acceptance.unitTestsPassed = testPassed;
acceptance.unitTestCount = numel(allResults);
acceptance.targetedPassed = targetPassed;
acceptance.targetedFalsePositives = ...
    targetFalsePositives;
acceptance.targetedFalseNegatives = ...
    targetFalseNegatives;
acceptance.freshRunCount = numel(freshResults);
acceptance.freshTruePositives = totalTruePositives;
acceptance.freshFalsePositives = totalFalsePositives;
acceptance.freshFalseNegatives = totalFalseNegatives;
acceptance.freshPrecision = precision;
acceptance.freshRecall = recall;
acceptance.freshMicroF1 = microF1;
acceptance.freshMeanLocalizationError = ...
    meanLocalizationError;
acceptance.multipleVictimsPrecision = ...
    multiplePrecision;
acceptance.multipleVictimsRecall = ...
    multipleRecall;
acceptance.freshValidationPassed = freshPassed;
acceptance.overallPassed = ...
    testPassed && targetPassed && freshPassed;
acceptance.targetedResults = targetResults;
acceptance.freshResults = freshResults;

disp("================================")
disp("ACCEPTANCE SUMMARY:")
disp(acceptance)

outputFolder = fullfile( ...
    fileparts(mfilename('fullpath')), ...
    "MeasurementResolvedAcceptanceResults");
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end
save(fullfile(outputFolder, ...
    "measurementResolvedAcceptance.mat"), ...
    'acceptance','allResults','targetResults','freshResults');

if acceptance.overallPassed
    disp("FINAL STATUS: PASS")
else
    disp("FINAL STATUS: NOT YET ACCEPTED")
end

end


function displayRun(result)

if ~result.runSucceeded
    disp("Scenario=" + string(result.scenarioType) + ...
        " | Seed=" + string(result.randomSeed) + ...
        " | RUN FAILED | " + ...
        string(result.errorIdentifier) + ...
        " | " + string(result.errorMessage))
    return;
end

lineText = ...
    "Scenario=" + string(result.scenarioType) + ...
    " | Seed=" + string(result.randomSeed) + ...
    " | Det=" + string(result.systemDetections) + ...
    " | TP=" + string(result.truePositives) + ...
    " | FP=" + string(result.falsePositives) + ...
    " | FN=" + string(result.falseNegatives) + ...
    " | F1=" + string(round(result.f1Score,3)) + ...
    " | Loc=" + ...
        string(round(result.localizationMeanError,3));
disp(lineText)

end


function value = finiteOrZero(value)

if ~isscalar(value) || ~isfinite(value)
    value = 0;
end

end
