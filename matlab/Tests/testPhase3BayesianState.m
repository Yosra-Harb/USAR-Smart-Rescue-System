    testCase, ...
    state.updateCount, ...
    0);

verifyEqual( ...
    testCase, ...
    state.nextTrackID, ...
    1);

end

%% ============================================================
% Test Invalid Grid Size
%% ============================================================

function testInvalidGridSizeIsRejected(testCase)

verifyError( ...
    testCase, ...
    @() initializeBayesianLocalizationState([0 10]), ...
    "initializeBayesianLocalizationState:InvalidGridSize");

verifyError( ...
    testCase, ...
    @() initializeBayesianLocalizationState([10 2.5]), ...
    "initializeBayesianLocalizationState:InvalidGridSize");

verifyError( ...
    testCase, ...
    @() initializeBayesianLocalizationState([10 10 10]), ...
    "initializeBayesianLocalizationState:InvalidGridSize");

end

