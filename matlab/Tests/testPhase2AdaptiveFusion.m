    weights.acoustic);
% مقارنة وزن الحراري بوزن الصوتي الموثوق

end

%% ============================================================
% Test Invalid Input Protection
%% ============================================================

function testInvalidValuesProduceValidWeights(testCase)

processedPacket = createTestPacket( ...
    [NaN, 0.60, Inf], ...
    [NaN, 0.80, 0.70]);
% إنشاء قراءات وموثوقيات تحتوي قيمًا غير صالحة

weights = calculateAdaptiveWeights(processedPacket);
% يجب أن تتعامل الدالة مع القيم غير الصالحة بأمان

weightVector = [ ...
    weights.radar, ...
    weights.thermal, ...
    weights.acoustic];

verifyTrue( ...
    testCase, ...
    all(isfinite(weightVector)));
% جميع الأوزان الناتجة يجب أن تكون أرقامًا صالحة

verifyGreaterThanOrEqual( ...
    testCase, ...
    weightVector, ...
    zeros(1,3));
% لا يُسمح بوجود أوزان سالبة

verifyEqual( ...
    testCase, ...
    sum(weightVector), ...
    1, ...
    'AbsTol', 1e-12);
% مجموع الأوزان يجب أن يبقى مساويًا لواحد

end

%% ============================================================
% Test Packet Helper
%% ============================================================

function processedPacket = ...
    createTestPacket(sensorValues, sensorReliabilities)

processedPacket = struct();
% إنشاء حزمة معالجة وهمية للاختبار

processedPacket.features = struct( ...
    'radarFeature', sensorValues(1), ...
    'thermalFeature', sensorValues(2), ...
    'acousticFeature', sensorValues(3));
% إضافة قراءات الحساسات الثلاثة

processedPacket.qualityReport = struct( ...
    'radarReliability', sensorReliabilities(1), ...
    'thermalReliability', sensorReliabilities(2), ...
    'acousticReliability', sensorReliabilities(3));
% إضافة موثوقية كل حساس

end