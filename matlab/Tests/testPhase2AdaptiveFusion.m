%% ============================================================
% Test Equal Sensor Conditions
%% ============================================================

function testEqualSensorsReceiveEqualWeights(testCase)

processedPacket = createTestPacket( ...
    [0.60, 0.60, 0.60], ...
    [0.80, 0.80, 0.80]);
% إنشاء ثلاث قراءات متساوية وموثوقيات متساوية

weights = calculateAdaptiveWeights(processedPacket);
% حساب الأوزان التكيفية

weightVector = [ ...
    weights.radar, ...
    weights.thermal, ...
    weights.acoustic];

verifyEqual( ...
    testCase, ...
    sum(weightVector), ...
    1, ...
    'AbsTol', 1e-12);
% التأكد من أن مجموع الأوزان يساوي واحدًا

verifyEqual( ...
    testCase, ...
    weightVector, ...
    [1/3, 1/3, 1/3], ...
    'AbsTol', 1e-12);
% الحساسات المتساوية يجب أن تحصل على أوزان متساوية

end

%% ============================================================
% Test Outlier Sensor Suppression
%% ============================================================

function testOutlierSensorReceivesLowerWeight(testCase)

processedPacket = createTestPacket( ...
    [0.65, 0.66, 0.10], ...
    [0.90, 0.90, 0.90]);
% الرادار والحراري متقاربان بينما الصوتي يعطي قراءة شاذة

weights = calculateAdaptiveWeights(processedPacket);
% حساب الأوزان التكيفية

verifyLessThan( ...
    testCase, ...
    weights.acoustic, ...
    weights.radar);
% يجب أن يكون وزن الحساس الصوتي الشاذ أقل من وزن الرادار

verifyLessThan( ...
    testCase, ...
    weights.acoustic, ...
    weights.thermal);
% يجب أن يكون وزن الحساس الصوتي الشاذ أقل من وزن الحراري

verifyEqual( ...
    testCase, ...
    weights.radar + weights.thermal + weights.acoustic, ...
    1, ...
    'AbsTol', 1e-12);
% التأكد من بقاء مجموع الأوزان مساويًا لواحد

end

